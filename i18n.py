def tr(lang, key, **kwargs):
    lang = normalize_language(lang)
    table = KO if lang == "ko" else EN
    value = table.get(key, EN.get(key, key.replace("_", " ").title()))
    try:
        return value.format(**kwargs)
    except Exception:
        return value

def category_name(lang, category):
    return category if normalize_language(lang) == "ko" else CATEGORY_EN.get(category, category)
